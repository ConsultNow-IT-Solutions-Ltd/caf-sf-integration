"""
CAF Compliance — plain-English summary (16:9 PowerPoint).

The same story as build_tech_deck.py told for someone who works with neither
system. Seven slides, no jargon, no screenshots: one governing image — a record
office and a front desk — carried the whole way through, because the single thing
a non-technical reader has to grasp is that the front desk never keeps its own
version of the truth.

Deliberately sparse. Bigger type and fewer words than either other deck: this one
is meant to be talked over, not read.

Content is the prose of "CAF Compliance - Plain English Summary.md", so the two
cannot drift into saying different things. Palette and chrome come from
build_deck, and the two-column helper from build_tech_deck, rather than being
copied.

    python build_layman_deck.py
"""

from pathlib import Path

from pptx import Presentation
from pptx.enum.text import PP_ALIGN
from pptx.util import Inches, Pt

from build_deck import (
    AMBER, CONFIDENTIAL, CONTENT_W, COVER_SUB, GREEN, LOGO, H, MARGIN, MAROON,
    NAVY, ROYAL, W, WHITE,
    blank, bullets, callout, chrome, rect, textbox, write,
)
from build_tech_deck import column

HERE = Path(__file__).resolve().parent
OUTPUT = HERE / "CAF Compliance - Plain English Summary.pptx"

# Bigger than the other decks. A layman audience reads the slide while listening,
# so anything that needs leaning in to read will simply not be read.
BODY = 15


def cover(prs):
    slide = blank(prs)
    rect(slide, 0, 0, W, H, NAVY)
    rect(slide, 0, H - Inches(0.22), W, Inches(0.22), ROYAL)

    if LOGO.exists():
        slide.shapes.add_picture(str(LOGO), MARGIN, Inches(0.7), width=Inches(1.7))

    tf = textbox(slide, MARGIN, Inches(2.6), Inches(11.0), Inches(2.2))
    write(tf, "CAF Compliance", size=54, color=WHITE, bold=True, first=True)
    write(tf, "What it is, and why we built it this way",
          size=22, color=COVER_SUB, space_before=10, line=1.2)

    rect(slide, MARGIN, Inches(4.7), Inches(2.2), Pt(3), ROYAL)

    tf = textbox(slide, MARGIN, Inches(5.02), Inches(11.0), Inches(1.1))
    write(tf, "In plain English", size=16, color=WHITE, first=True)

    tf = textbox(slide, MARGIN, H - Inches(0.95), Inches(11.0), Inches(0.4))
    write(tf, CONFIDENTIAL, size=9, color=COVER_SUB, first=True)


def what(prs):
    slide = blank(prs)
    top = chrome(slide, "Proving the important things are looked after",
                 "Some business applications matter enough that the company has to keep proving they are "
                 "properly cared for.")

    bullets(slide, [
        ("They are backed up, and can actually be restored.",
         "Not that a backup job ran — that someone has checked it would work."),
        ("There is a tested plan for a serious failure.",
         "And an agreed answer to how quickly the application must be back."),
        ("Someone accountable has put their name to it.",
         "A person, on the record, not a green tick generated by a system."),
    ], top + Inches(0.4), size=BODY, gap=16)

    callout(slide, Inches(5.5),
            "And it is never finished. Every application, against every standard, on a repeating cycle.",
            height=Inches(0.68))


def problem(prs):
    slide = blank(prs)
    top = chrome(slide, "The rules were never the problem",
                 "All of this already worked. The difficulty was at the last step — getting people to sign.")

    bullets(slide, [
        ("The machinery was sound.",
         "The standards, the repeating schedule, the chasing of anything overdue, the audit trail. "
         "None of it needed changing."),
        ("But the cost grew with the number of people we asked.",
         "Everyone who had to sign something off needed an account in a system they otherwise never "
         "opened — and every one of those accounts costs money."),
        ("So take-up was poor, and the record went stale.",
         "Not because anyone disagreed with the checks. Because of where they had to go to do them."),
    ], top + Inches(0.34), size=BODY, gap=14)

    callout(slide, Inches(4.78),
            "“I'm not logging into another system just for this.”  That sentence is the whole problem.",
            height=Inches(0.7), accent=MAROON)


def built(prs):
    slide = blank(prs)
    chrome(slide, "We moved the front door, not the machinery",
           "The rules stayed exactly where they were. What changed is where people go to use them.")

    col_w = (CONTENT_W - Inches(0.4)) / 2
    right = MARGIN + col_w + Inches(0.4)

    column(slide, MARGIN, Inches(2.16), col_w, "The record office", NAVY, [
        "Holds the official record.",
        "Decides what is due, what is late, and what counts as compliant.",
        "Every decision is still made here, under the rules that already existed.",
    ], size=13, gap=13, height=Inches(2.0))

    column(slide, right, Inches(2.16), col_w, "The front desk", ROYAL, [
        "Where people actually turn up — the system they already have open all day.",
        "Shows them their applications, takes their evidence, takes their sign-off.",
        "Passes each request to the record office and shows what came back.",
    ], size=13, gap=13, height=Inches(2.0))

    callout(slide, Inches(4.92),
            "The front desk never keeps its own version of the truth. It shows a copy of the official "
            "record — so the two can never quietly disagree about what was decided.",
            height=Inches(0.86), accent=GREEN)

    tf = textbox(slide, MARGIN, Inches(6.02), CONTENT_W, Inches(0.4))
    write(tf, "The person doing the work never sees the join.",
          size=14, color=ROYAL, bold=True, italic=True, first=True, align=PP_ALIGN.CENTER)


def checking(prs):
    slide = blank(prs)
    top = chrome(slide, "A copy nobody checks is worse than no copy",
                 "Because people believe it. So something has to be watching.")

    bullets(slide, [
        ("The system checks itself, and says so.",
         "It compares the copy against the official record and reports any disagreement, rather than "
         "waiting for someone to notice a number that looks wrong."),
        ("It only ever corrects the copy — never the original.",
         "If the two disagree, the official record wins by definition. There is nothing to negotiate."),
        ("It never repairs anything on its own.",
         "A person sees the difference and decides. Correcting things automatically risks turning a small "
         "display problem into a real one in the system of record."),
    ], top + Inches(0.34), size=BODY, gap=14)


def evidence(prs):
    slide = blank(prs)
    top = chrome(slide, "Evidence, and who is allowed to judge it",
                 "The two jobs are kept deliberately apart.")

    bullets(slide, [
        ("The owner provides the proof.",
         "Uploaded against the specific check it belongs to, without leaving the system they already use."),
        ("Somebody else judges it.",
         "The approver can see the evidence but cannot add to it. Gathering proof and ruling on it are "
         "different jobs, done by different people."),
        ("No evidence, no sign-off.",
         "An attestation with nothing behind it is refused outright, rather than accepted and queried later."),
        ("Every file is kept in both places.",
         "So an auditor can always be handed the copy held in the official record."),
    ], top + Inches(0.3), size=13.5, gap=11)

    callout(slide, Inches(4.68),
            "Separating the two is what makes a sign-off worth anything: the person who did the work is not "
            "the person who says it was done properly.", height=Inches(0.78), accent=GREEN)


def stands(prs):
    slide = blank(prs)
    chrome(slide, "Where this stands")

    col_w = (CONTENT_W - Inches(0.4)) / 2
    right = MARGIN + col_w + Inches(0.4)

    column(slide, MARGIN, Inches(1.7), col_w, "Built, and demonstrated on real data", GREEN, [
        "The at-a-glance view of every application and every standard.",
        "Drill-down from that view to the individual piece of work.",
        "Evidence upload and sign-off, end to end.",
        "The checker that keeps the two systems honest.",
    ], size=12.5, gap=12, height=Inches(2.6))

    column(slide, right, Inches(1.7), col_w, "Still to come", AMBER, [
        "A way in for people who hold no licence at all — the commercial half of the original idea.",
        "Automated safety checks, before this carries real work.",
        "Queuing, so a brief outage waits rather than fails.",
    ], size=12.5, gap=12, height=Inches(2.6))

    callout(slide, Inches(5.0),
            "None of what remains touches the compliance rules themselves. Those were never the problem, "
            "and they have not been changed.", height=Inches(0.78))

    tf = textbox(slide, MARGIN, Inches(6.06), CONTENT_W, Inches(0.4))
    write(tf, "The engine is untouched. Everything we built is delivery around it.",
          size=14, color=ROYAL, bold=True, italic=True, first=True, align=PP_ALIGN.CENTER)


def main():
    prs = Presentation()
    prs.slide_width, prs.slide_height = W, H

    for builder in (cover, what, problem, built, checking, evidence, stands):
        builder(prs)

    prs.save(OUTPUT)
    print(f"{len(prs.slides.__iter__.__self__._sldIdLst)} slides -> {OUTPUT}")


if __name__ == "__main__":
    main()
